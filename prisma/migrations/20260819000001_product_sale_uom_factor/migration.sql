-- 换算系数改挂商品（20260819）
--
-- 「1 CASE 等于多少」是**商品**的属性，不是 CASE 这个单位的属性：
-- 生产库里 `...10*700g CASE`（一箱 10 包）与 `...30*62g CASE`（一箱 30 包）同名不同量。
-- 全局 Uom.factor 承担不了这件事 —— 它在生产库 Unit 类目下干脆全是 1，
-- 导致多规格报价切了单位价格不变、库存也不换算。
--
-- 默认 1 = 与改造前行为完全一致：已有的 5 行配置（生产库快照）在迁移后
-- 仍按 1:1 处理，不会有任何一张历史单据的金额或库存被这次迁移改动。
ALTER TABLE "ProductSaleUom" ADD COLUMN "factor" DECIMAL(14,6) NOT NULL DEFAULT 1;
