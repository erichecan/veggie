-- 销售单印发票号（20260920）
-- ============================================================================
-- 客户要求：销售单上的「Sale Order NO」改成「Invoice No.」，客户拿到这张纸就能
-- 直接交给会计进账。号要与 Odoo 历史发票同一序列（V#####）。
--
-- 生产库现状（20260920 实测）：
--   Invoice 表 148,285 张，其中 V 序列 25,223 张，号段 V1 ~ V59085，断号 33,862 个。
--   断号这么多说明 V 号是 Odoo 发的、我们只导入了一部分。最新一张 V59085 停在 2026-07-13。
--   客户拍板从 V59086 接着往下排（方案 B）。
--
-- ⚠️ 前提未验证：如果 Odoo 12 仍在开票，两边会撞号。因此：
--   1. 本列加 UNIQUE —— 本系统内部绝不重号；
--   2. 发号时同时避开 Invoice.name 已占用的号（见 lib/invoice-number.ts）；
--   3. 号段起点是代码里的常量，将来要挪开只改一行。

ALTER TABLE "Order" ADD COLUMN "invoiceNo" TEXT;

-- 一个号只能挂一张订单。撞号时写入直接失败，不会静默产生两张同号的单。
CREATE UNIQUE INDEX "Order_invoiceNo_key" ON "Order"("invoiceNo");
